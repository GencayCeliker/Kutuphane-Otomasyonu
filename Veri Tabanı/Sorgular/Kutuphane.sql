CREATE TABLE TblUYELER
(
UyeId INT IDENTITY PRIMARY KEY,
UyeAd NVARCHAR (250) NOT NULL,
UyeSoyad NVARCHAR (250) NOT NULL,
UyeTCKimlik NCHAR(11) UNIQUE CHECK(UyeTCKimlik LIKE '[0-9][0-9][0-9][0-9][0-9][0-9][0-9][0-9][0-9][0-9][02468]')NOT NULL,
UyeAdres NVARCHAR(250) NOT NULL,
UyeTel NCHAR(10) NOT NULL,
)
GO
--ISBN KİTAP BARKODU
CREATE TABLE TblKITAPLAR
(
KitapId INT IDENTITY PRIMARY KEY,
ISBN NCHAR(13) UNIQUE CHECK(ISBN LIKE'[0-9][0-9][0-9][0-9][0-9][0-9][0-9][0-9][0-9][0-9][0-9][0-9][0-9]') NOT NULL,
KitapAdi NVARCHAR(250) NOT NULL,
Sayafa INT NOT NULL,
Adet INT NOT NULL,
